"""Выравнивание масштабов синтетики и реальных данных (sim-to-real).

Проблема, ради которой существует модуль. 1D-модель теплопередачи даёт
контраст в 2-3 раза сильнее, чем реальная панель: она не воспроизводит
боковую диффузию тепла, разброс излучательной способности и потери на
стенках сот (ARCHITECTURE.md раздел 10). Сеть, обученная на синтетике,
принимает более слабый реальный сигнал за признак пустой ячейки —
измерено: свежий этап A уверенно предсказывал «пусто» для всех зон воды
на water1 (логиты 0.3-3.3 в пользу класса 0 при истине «вода»).

Три способа закрыть разрыв, все реализованы здесь:

* `SCALE` — эмпирический калибровочный множитель для синтетики. Быстро,
  но привязан к конкретной установке: другая лампа или другое покрытие
  панели потребуют пересчёта.
* `robust_amplitude_norm` — перцентильная нормировка каждого примера на
  собственный размах. Инвариантна к абсолютному масштабу по построению,
  калибровки не требует. Цена: теряется абсолютная амплитуда как признак,
  остаётся только форма кривой. Для различения вода/смола это приемлемо —
  их разделяет именно форма (раздел 0), — но для градаций заполнения
  амплитуда важна, поэтому нормировка применяется поканально и
  контролируемо.
* Нормировка на опорную синтетическую кривую (3D normalization,
  Vavilov & Burleigh) — деление реальной последовательности на
  синтетическую, посчитанную для того же случая. Здесь не реализована:
  требует посчитать синтетику под геометрию каждой записи, что при трёх
  объектах дороже, чем два способа выше.

Перцентили вместо min/max: контраст на границах зон и в шумных пикселях
даёт редкие выбросы, и деление на максимум сжимало бы полезный диапазон
в узкую полосу вокруг нуля.
"""
from __future__ import annotations

import numpy as np

#: Нижний и верхний перцентили для robust-нормировки. 2/98 отсекают
#: выбросы на переходе контраста через ноль, не трогая рабочий диапазон.
LOW_PERCENTILE: float = 2.0
HIGH_PERCENTILE: float = 98.0

#: Минимальный размах, ниже которого нормировка не применяется: пример
#: без сигнала (пустая запись, брак) иначе усилился бы до шума.
MIN_SPAN: float = 1e-6


def robust_amplitude_norm(
    tensor: np.ndarray,
    axis: tuple[int, ...],
    low: float = LOW_PERCENTILE,
    high: float = HIGH_PERCENTILE,
) -> np.ndarray:
    """Приводит амплитуду к единичному размаху по перцентилям.

    Каждый срез вдоль `axis` центрируется на своей медиане и делится на
    межперцентильный размах. Результат сопоставим между синтетикой и
    реальными данными независимо от того, во сколько раз отличается
    абсолютный уровень сигнала.

    Args:
        tensor: массив признаков произвольной формы.
        axis: оси, по которым считается статистика (обычно временная и
            пространственные, но не канальная — каналы имеют разный смысл
            и разный масштаб, смешивать их нельзя).
        low: нижний перцентиль.
        high: верхний перцентиль.

    Returns:
        Массив той же формы, float32.

    Raises:
        ValueError: если `low >= high`.
    """
    if low >= high:
        raise ValueError(f"low={low} должен быть меньше high={high}")

    data = tensor.astype(np.float64)
    lo = np.percentile(data, low, axis=axis, keepdims=True)
    hi = np.percentile(data, high, axis=axis, keepdims=True)
    median = np.median(data, axis=axis, keepdims=True)

    span = hi - lo
    span = np.where(span < MIN_SPAN, 1.0, span)
    return ((data - median) / span).astype(np.float32)


def apply_channel_norm(tensor: np.ndarray) -> np.ndarray:
    """Robust-нормировка трёхканального входа модели, поканально.

    Args:
        tensor: (C, T, H, W) — выход `build_input_tensor` или его
            синтетический аналог.

    Returns:
        (C, T, H, W) float32 с выровненной амплитудой каждого канала.
    """
    if tensor.ndim != 4:
        raise ValueError(f"Ожидается (C, T, H, W), получено {tensor.shape}")
    # Статистика по (T, H, W) внутри каждого канала: канал сохраняет свою
    # роль, но его абсолютный уровень перестаёт зависеть от установки.
    return robust_amplitude_norm(tensor, axis=(1, 2, 3))


def apply_curve_norm(curves: np.ndarray) -> np.ndarray:
    """Robust-нормировка пачки одномерных кривых синтетики.

    Args:
        curves: (N, C, T) — трёхканальные признаки отдельных кривых.

    Returns:
        (N, C, T) float32.
    """
    if curves.ndim != 3:
        raise ValueError(f"Ожидается (N, C, T), получено {curves.shape}")
    # По времени внутри каждого (пример, канал).
    return robust_amplitude_norm(curves, axis=(2,))
