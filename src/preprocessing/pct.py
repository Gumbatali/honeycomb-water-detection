"""Principal Component Thermography — амплитудно-устойчивое представление.

PCT (Rajic, 2002) — стандарт импульсной термографии: последовательность
кадров раскладывается по эмпирическим ортогональным функциям (EOF), и
дефекты проявляются в первых компонентах. В обзорах по нейросетевой
термографии PCT используется именно как предобработка перед сетью, а не
как самостоятельный детектор.

Зачем он здесь. Две первые попытки закрыть sim-to-real разрыв упирались в
амплитуду: синтетика даёт контраст втрое сильнее реального (см.
`domain_align`, `SIM_TO_REAL_SCALE`). PCT снимает вопрос иначе — компоненты
нормированы по построению (сингулярные векторы единичной длины), поэтому
представление зависит от ФОРМЫ пространственно-временной картины, а не от
того, во сколько раз сильнее сигнал. Это тот же аргумент, по которому
раздел 0 архитектуры требует различать вещества по форме кривой.

Ограничение, которое надо помнить: нормировка по построению убирает
абсолютную амплитуду, а она несёт информацию о количестве воды. Поэтому
PCT-признаки дополняют контраст, а не заменяют его.
"""
from __future__ import annotations

import numpy as np

#: Число главных компонент по умолчанию. Первые 3-5 EOF несут почти всю
#: полезную дисперсию; дальше идёт шум камеры.
DEFAULT_N_COMPONENTS: int = 4

#: Минимальная дисперсия, ниже которой пиксель считается «мёртвым» и не
#: участвует в разложении: постоянные пиксели дают нулевую строку и портят
#: нормировку.
MIN_PIXEL_VARIANCE: float = 1e-12


def principal_component_thermography(
    cube: np.ndarray, n_components: int = DEFAULT_N_COMPONENTS
) -> tuple[np.ndarray, np.ndarray]:
    """Раскладывает куб термограмм по эмпирическим ортогональным функциям.

    Каждый пиксель центрируется по своей временной средней, затем матрица
    (пиксели x время) раскладывается по SVD. Пространственные компоненты —
    это карты дефектов, временные — соответствующие им профили остывания.

    Args:
        cube: (H, W, N_frames) — контраст или сырой перегрев.
        n_components: сколько первых компонент вернуть.

    Returns:
        ``(spatial (H, W, n_components), temporal (n_components, N_frames))``
        — обе величины float32. Пространственные компоненты нормированы:
        их масштаб не зависит от абсолютной амплитуды входа.

    Raises:
        ValueError: при неверной форме входа или `n_components` больше числа
            доступных компонент.
    """
    if cube.ndim != 3:
        raise ValueError(f"Ожидается куб (H, W, N), получено {cube.shape}")

    height, width, n_frames = cube.shape
    max_components = min(height * width, n_frames)
    if not 1 <= n_components <= max_components:
        raise ValueError(
            f"n_components={n_components} вне диапазона [1, {max_components}]"
        )

    matrix = cube.reshape(-1, n_frames).astype(np.float64)
    # Средний уровень пикселя — якорь для фиксации знака компонент (см.
    # ниже). Снимается ДО центрирования, после которого он тождественно
    # равен нулю.
    pixel_level = matrix.mean(axis=1)
    # Центрирование по времени: PCT ищет отклонения от собственного
    # остывания пикселя, а не общий уровень температуры.
    matrix = matrix - pixel_level[:, None]

    # Мёртвые пиксели обнуляют строку и делают SVD вырожденным.
    variance = matrix.var(axis=1)
    alive = variance > MIN_PIXEL_VARIANCE
    if not np.any(alive):
        raise ValueError("Все пиксели постоянны во времени — разложение невозможно")

    u, singular, vt = np.linalg.svd(matrix[alive], full_matrices=False)

    spatial = np.zeros((matrix.shape[0], n_components), dtype=np.float64)
    spatial[alive] = u[:, :n_components] * singular[:n_components]
    temporal = vt[:n_components]

    # Знак сингулярных векторов произволен — SVD определяет пару (u, v) с
    # точностью до общего знака. Без фиксации одна и та же физическая
    # картина приходит с разным знаком на разных записях, и модель видит
    # их как разные классы. Измерено на water1/water2: модуль разделения
    # вода-смола по EOF3 совпадал (1.004 против 1.002), а знак был
    # противоположным.
    #
    # Фиксируем по корреляции пространственной карты с усреднённым по
    # времени входом. Это единственный внешний якорь: сам вход знака не
    # меняет, тогда как любая величина, выведенная из EOF (перекос карты,
    # тренд временного профиля), переворачивается вместе с компонентой и
    # фиксировать её бесполезно — попытка привязаться к тренду не дала
    # согласования ни на одной из трёх записей.
    #
    # Опорная величина — средний контраст пикселя: у дефектных зон он выше
    # фонового, и это свойство физики, одинаковое для всех панелей.
    anchor = pixel_level - pixel_level.mean()
    projection = spatial.T @ anchor
    signs = np.where(projection < 0.0, -1.0, 1.0)

    spatial = spatial * signs
    temporal = temporal * signs[:, None]

    return (
        spatial.reshape(height, width, n_components).astype(np.float32),
        temporal.astype(np.float32),
    )


def pct_feature_maps(
    cube: np.ndarray, n_components: int = DEFAULT_N_COMPONENTS
) -> np.ndarray:
    """PCT-карты, приведённые к единичному разбросу — готовый вход модели.

    Каждая компонента делится на своё стандартное отклонение: абсолютный
    масштаб EOF зависит от энергии сигнала (а значит, от мощности лампы и
    от того, синтетика это или реальная запись), тогда как пространственный
    рисунок — нет.

    ВНИМАНИЕ: знак компонент выше первой не воспроизводится между записями
    (см. `principal_component_thermography`). Для признаков, которые пойдут
    в модель, используйте `sign_invariant_feature_maps`.

    Args:
        cube: (H, W, N_frames).
        n_components: число компонент.

    Returns:
        (n_components, H, W) float32.
    """
    spatial, _ = principal_component_thermography(cube, n_components)
    maps = np.moveaxis(spatial, 2, 0)

    scale = maps.std(axis=(1, 2), keepdims=True)
    scale = np.where(scale < MIN_PIXEL_VARIANCE, 1.0, scale)
    return (maps / scale).astype(np.float32)


def sign_invariant_feature_maps(
    cube: np.ndarray, n_components: int = DEFAULT_N_COMPONENTS
) -> np.ndarray:
    """PCT-карты, не зависящие от произвольного знака компонент.

    Якорь по среднему уровню пикселя (см.
    `principal_component_thermography`) стабилизирует только первую
    компоненту: у остальных проекция на якорь близка к нулю, и её знак
    случаен. Измерено на трёх записях — EOF1 согласован (вода 2.53 / 2.26 /
    2.35), EOF2 и EOF3 приходят с разными знаками.

    Взятие модуля не годится: вода и смола лежат ПО РАЗНЫЕ СТОРОНЫ от нуля
    (на water1 по EOF3 это -0.22 против +0.78), и модуль их схлопывает —
    замер показал падение разделения с 1.0 / 1.0 / 1.7 до 0.14 / 0.04 / 0.7.

    Вместо этого знак каждой компоненты выравнивается по её собственному
    ФОНУ: пиксели вне размеченных зон физически одинаковы на всех панелях,
    поэтому «фон положителен» — воспроизводимое условие, не зависящее ни от
    раскладки зон, ни от произвола SVD. Расстояние между классами при этом
    сохраняется полностью.

    Args:
        cube: (H, W, N_frames).
        n_components: число компонент.

    Returns:
        (n_components, H, W) float32.
    """
    maps = pct_feature_maps(cube, n_components)

    # Медиана по кадру — устойчивая оценка фонового уровня: дефекты
    # занимают меньшую часть площади, поэтому медиана приходится на фон.
    background = np.median(maps, axis=(1, 2), keepdims=True)
    signs = np.where(background < 0.0, -1.0, 1.0)
    return (maps * signs).astype(np.float32)
